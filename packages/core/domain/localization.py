def normalize_locale(value: str | None) -> SupportedLocale:
    code = (
        (value if isinstance(value, str) else "it")
        .strip()
        .lower()
        .replace("_", "-")
        .split("-", 1)[0]
    )
    return cast(SupportedLocale, code if code in SUPPORTED_LOCALES else "it")


def language_name(value: str | None) -> str:
    return LANGUAGE_NAMES[normalize_locale(value)]


