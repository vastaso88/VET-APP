"""Pets in Ricordi do not take a place of the plan (owner decision 2026-11-16):
the backend counts only the active ones, and the database (plan_access_rules.sql,
generated by scripts/maintenance/gen_plan_access_sql.py) says the same for the
writes the app makes directly, including bringing a pet back from Ricordi."""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from packages.core.application.services.create_pet_profile import (
    CreatePetProfileInput,
    CreatePetProfileService,
)
from packages.core.domain.pet_profile.models import PetProfile
from packages.core.domain.subscription.limits import LIMITS_BY_PLAN, TRIAL_LIMITS, PlanLimits
from packages.infrastructure.persistence.in_memory_repositories import InMemoryPetProfileRepository
from packages.shared.errors.base import PlanLimitError

ROOT = Path(__file__).resolve().parents[2]
PLUS = LIMITS_BY_PLAN["plus"]


def _service(
    pets: InMemoryPetProfileRepository, limits: PlanLimits | None = PLUS
) -> CreatePetProfileService:
    return CreatePetProfileService(pets, owner_limits=lambda _owner, _email: limits)


def _fill(pets: InMemoryPetProfileRepository, owner: str, *, active: int, memorial: int) -> None:
    for index in range(active):
        pets.save(PetProfile(owner_id=owner, name=f"Active {index}", species="Cane"))
    for index in range(memorial):
        pets.save(
            PetProfile(owner_id=owner, name=f"Ricordo {index}", species="Cane", is_memorial=True)
        )


def _create(service: CreatePetProfileService, owner: str, name: str = "New") -> PetProfile:
    return service.execute(
        CreatePetProfileInput(owner_id=owner, name=name, species="Gatto")
    ).pet_profile


# --- the backend count -----------------------------------------------------------------


def test_a_plan_full_of_pets_still_has_room_for_one_if_one_is_in_ricordi() -> None:
    pets = InMemoryPetProfileRepository()
    _fill(pets, "owner-a", active=PLUS.max_pets - 1, memorial=1)  # as many pets as the plan

    created = _create(_service(pets), "owner-a")

    assert created.owner_id == "owner-a"
    assert len(pets.list_by_owner("owner-a")) == PLUS.max_pets + 1  # one is in Ricordi


def test_pets_in_ricordi_never_free_more_than_their_own_places() -> None:
    pets = InMemoryPetProfileRepository()
    _fill(pets, "owner-a", active=PLUS.max_pets, memorial=3)

    with pytest.raises(PlanLimitError) as error:
        _create(_service(pets), "owner-a")

    assert error.value.kind == "pets" and error.value.limit == PLUS.max_pets


def test_moving_a_pet_to_ricordi_frees_its_place() -> None:
    pets = InMemoryPetProfileRepository()
    _fill(pets, "owner-a", active=PLUS.max_pets, memorial=0)
    with pytest.raises(PlanLimitError):
        _create(_service(pets), "owner-a")

    moved = pets.list_by_owner("owner-a")[0]
    pets.save(moved.model_copy(update={"is_memorial": True}))

    assert _create(_service(pets), "owner-a").name == "New"


def test_many_pets_in_ricordi_do_not_block_anyone() -> None:
    pets = InMemoryPetProfileRepository()
    _fill(pets, "owner-a", active=0, memorial=PLUS.max_pets * 3)

    for index in range(PLUS.max_pets):
        _create(_service(pets), "owner-a", f"Pet {index}")

    with pytest.raises(PlanLimitError):
        _create(_service(pets), "owner-a", "One too many")


def test_the_trial_counts_the_same_way() -> None:
    pets = InMemoryPetProfileRepository()
    _fill(pets, "owner-a", active=TRIAL_LIMITS.max_pets, memorial=2)

    with pytest.raises(PlanLimitError):
        _create(_service(pets, TRIAL_LIMITS), "owner-a")


def test_a_developer_account_has_no_limit_whatever_is_in_ricordi() -> None:
    pets = InMemoryPetProfileRepository()
    _fill(pets, "owner-a", active=PLUS.max_pets * 2, memorial=2)

    assert _create(_service(pets, None), "owner-a")


def test_user_b_is_not_touched_by_what_user_a_has_in_ricordi() -> None:
    pets = InMemoryPetProfileRepository()
    _fill(pets, "owner-a", active=PLUS.max_pets, memorial=PLUS.max_pets)  # A is full
    _fill(pets, "owner-b", active=PLUS.max_pets - 1, memorial=5)  # B has one place left

    assert _create(_service(pets), "owner-b").owner_id == "owner-b"
    with pytest.raises(PlanLimitError):  # and now B is full too, whatever A has
        _create(_service(pets), "owner-b", "Next")
    assert len(pets.list_by_owner("owner-a")) == PLUS.max_pets * 2  # A's pets untouched


# --- the database (the app's direct writes) ---------------------------------------------------


def _sql() -> str:
    text = (ROOT / "scripts/setup/plan_access_rules.sql").read_text(encoding="utf-8")
    return "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("--"))


def _pet_limit_function() -> str:
    match = re.search(r"function public\.plan_access_pet_limit\(\).*?\$\$;", _sql(), re.S)
    assert match is not None
    return match.group(0)


def test_the_script_makes_sure_the_ricordi_column_exists() -> None:
    assert (
        "alter table public.pet_profiles add column if not exists is_memorial "
        "boolean not null default false;"
    ) in _sql()


def test_a_pet_born_in_ricordi_or_moved_there_takes_no_place() -> None:
    body = _pet_limit_function()

    early = body.index("coalesce(new.is_memorial, false)")
    assert early < body.index("pg_advisory_xact_lock"), "decided before counting"
    assert "return new;" in body[early : early + 120]


def test_only_the_return_from_ricordi_adds_a_pet_on_update() -> None:
    body = _pet_limit_function()

    update = body.index("tg_op = 'UPDATE'")
    # OLD does not exist in an insert: it is only read inside the update branch.
    assert body.index("old.is_memorial") > update
    assert "if not coalesce(old.is_memorial, false) then" in body
    assert body.count("old.") == 1


def test_the_count_is_of_active_pets_without_the_row_that_comes_back() -> None:
    body = _pet_limit_function()

    assert "p.owner_id = new.owner_id and not p.is_memorial and p.id <> new.id" in body
    assert body.index("pg_advisory_xact_lock") < body.index("select count(*)")


def test_the_trigger_runs_on_insert_and_on_update() -> None:
    assert re.search(
        r"create trigger plan_access_20_pet_limit\s+before insert or update "
        r"on public\.pet_profiles",
        _sql(),
    )


def test_the_return_is_refused_with_the_same_code_the_app_already_handles() -> None:
    body = _pet_limit_function()

    assert "errcode = 'PT403'" in body and "message = 'plan_limit_reached'" in body
    assert "detail = 'pets'" in body and "hint = limit_count::text" in body


def test_the_ricordi_read_only_trigger_lets_the_return_through() -> None:
    """The plan trigger decides the return; the Ricordi trigger must not stop it
    first (it only freezes a profile that is in Ricordi before AND after)."""
    ricordi = (ROOT / "scripts/setup/ricordi_animali.sql").read_text(encoding="utf-8")

    assert "if not (old.is_memorial and new.is_memorial) then" in ricordi
    # Triggers run in name order: the plan check ("plan_access_20") is first.
    assert "plan_access_20_pet_limit" < "ricordi_10_profile_read_only"
