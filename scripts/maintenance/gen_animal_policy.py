"""Writes the two copies of the Mercatino "no animals" rule that cannot import
the Python module:

* apps/mobile_app/lib/features/marketplace/domain/animal_policy_patterns.dart
* scripts/setup/marketplace_no_animals.sql

The rule itself lives in packages/core/domain/marketplace/animal_policy.py.
``python scripts/maintenance/gen_animal_policy.py`` rewrites both;
``--check`` exits 1 when one is out of date (tests/unit/test_animal_policy.py
runs it).
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from packages.core.domain.marketplace.animal_policy import (  # noqa: E402
    ACCENT_FROM,
    ACCENT_TO,
    PATTERN_SOURCES,
)

DART_PATH = ROOT / "apps/mobile_app/lib/features/marketplace/domain/animal_policy_patterns.dart"
SQL_PATH = ROOT / "scripts/setup/marketplace_no_animals.sql"

_ORDER = (
    "object_target",
    "animal_then_offer",
    "offer_then_animal",
    "animal_then_offer_near",
    "offer_then_animal_near",
    "animal_adjacent_offer",
    "young_of",
    "young",
    "object",
    "adoption",
)


def _dart_source(key: str) -> str:
    return PATTERN_SOURCES[key].replace("<B>", r"\b").replace("</B>", r"\b")


def _pg_source(key: str) -> str:
    return PATTERN_SOURCES[key].replace("<B>", r"\m").replace("</B>", r"\M")


def render_dart() -> str:
    lines = [
        "// GENERATED by scripts/maintenance/gen_animal_policy.py from",
        "// packages/core/domain/marketplace/animal_policy.py - do not edit by hand.",
        "// The Mercatino sells things for animals, never animals: these are the same",
        "// patterns the backend and the database use (see animal_policy.dart).",
        "",
        f"const animalPolicyAccentFrom = '{ACCENT_FROM}';",
        f"const animalPolicyAccentTo = '{ACCENT_TO}';",
        "",
        "const animalPolicyPatterns = <String, String>{",
    ]
    for key in _ORDER:
        lines.append(f"  '{key}':")
        lines.append(f"      r'{_dart_source(key)}',")
    lines.append("};")
    return "\n".join(lines) + "\n"


def render_sql() -> str:
    p = {key: _pg_source(key) for key in _ORDER}
    return f"""-- Mercatino: niente animali, solo oggetti per animali (decisione del
-- proprietario, 2026-10-26, tutti i paesi). GENERATO da
-- scripts/maintenance/gen_animal_policy.py a partire da
-- packages/core/domain/marketplace/animal_policy.py: non modificare a mano.
--
-- Cosa fa: nasconde (NON cancella) gli annunci che offrono, regalano o
-- scambiano animali, mettendoli in stato 'removed_policy'. Il backend e l'app
-- mostrano solo gli annunci 'active'. E' idempotente: si puo' rilanciare.
--
-- COME USARLO
--   1. Eseguire PRIMA la parte A (anteprima): dice quanti annunci verrebbero
--      nascosti e ne mostra 50 titoli da controllare a occhio.
--   2. Se l'elenco e' sensato, eseguire la parte B (nasconde gli annunci).
--   3. Per riattivare un annuncio nascosto per errore:
--        update public.marketplace_listings set status = 'active'
--        where id = '<id>';
--      (e non verra' nascosto di nuovo finche' resta 'active': la parte B si
--      lancia una volta sola, non ad ogni avvio.)
--
-- La regola e' la stessa del backend (stesse liste di parole, stesso
-- procedimento): vedi la docstring di animal_policy.py. Le parole sono
-- confrontate intere, senza accenti e senza maiuscole.

create or replace function public.listing_text_offers_animals(raw text, about_accessory boolean)
returns boolean
language plpgsql
immutable
set search_path = public
as $fn$
declare
    t text;
    own_accessory boolean;
begin
    t := ' ' || trim(regexp_replace(
        translate(lower(coalesce(raw, '')), '{ACCENT_FROM}', '{ACCENT_TO}'),
        '[^a-z0-9]+', ' ', 'g')) || ' ';
    if trim(t) = '' then
        return false;
    end if;
    own_accessory := t ~ '{p["object"]}';
    -- Un animale nominato solo come destinatario di un accessorio ("per gatto",
    -- "cuccia per cuccioli", "guinzaglio cane") non conta.
    t := regexp_replace(' ' || t, '{p["object_target"]}', ' ', 'g');
    t := regexp_replace(t, ' +', ' ', 'g');

    if t ~ '{p["adoption"]}' then
        return true;
    end if;
    if t ~ '{p["animal_adjacent_offer"]}' then
        return true;
    end if;
    if own_accessory then
        if t ~ '{p["animal_then_offer_near"]}' or t ~ '{p["offer_then_animal_near"]}' then
            return true;
        end if;
    else
        if t ~ '{p["animal_then_offer"]}' or t ~ '{p["offer_then_animal"]}' then
            return true;
        end if;
    end if;
    if t ~ '{p["young_of"]}' then
        return true;
    end if;
    return t ~ '{p["young"]}' and not about_accessory;
end;
$fn$;

create or replace function public.listing_offers_animals(title text, description text)
returns boolean
language plpgsql
immutable
set search_path = public
as $fn$
declare
    combined text;
    about_accessory boolean;
begin
    combined := ' ' || trim(regexp_replace(
        translate(lower(coalesce(title, '') || ' ' || coalesce(description, '')),
                  '{ACCENT_FROM}', '{ACCENT_TO}'),
        '[^a-z0-9]+', ' ', 'g')) || ' ';
    about_accessory := combined ~ '{p["object"]}';
    return public.listing_text_offers_animals(title, about_accessory)
        or public.listing_text_offers_animals(description, about_accessory);
end;
$fn$;

revoke all on function public.listing_text_offers_animals(text, boolean)
    from public, anon, authenticated;
revoke all on function public.listing_offers_animals(text, text)
    from public, anon, authenticated;

-- Un utente normale non deve poter riattivare un annuncio nascosto: la guardia
-- del database tratta 'removed_policy' come 'removed' (stessa funzione di
-- supabase_schema.sql).
create or replace function public.guard_marketplace_listing()
returns trigger
language plpgsql
set search_path = public
as $$
begin
    new.latitude := round(new.latitude::numeric, 2)::double precision;
    new.longitude := round(new.longitude::numeric, 2)::double precision;

    if current_user in ('authenticated', 'anon') then
        if tg_op = 'INSERT' then
            new.report_count := 0;
            new.status := 'active';
        else
            new.owner_id := old.owner_id;
            new.created_at := old.created_at;
            new.report_count := old.report_count;
            if old.status in ('removed', 'removed_policy')
               or new.status in ('removed', 'removed_policy') then
                new.status := old.status;
            end if;
        end if;
    end if;

    return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- PARTE A - ANTEPRIMA (non modifica nulla)
-- ---------------------------------------------------------------------------
select count(*) as annunci_da_nascondere
from public.marketplace_listings
where status in ('active', 'reserved')
  and public.listing_offers_animals(title, description);

select id, title, left(coalesce(description, ''), 80) as description, country, created_at
from public.marketplace_listings
where status in ('active', 'reserved')
  and public.listing_offers_animals(title, description)
order by created_at desc
limit 50;

-- ---------------------------------------------------------------------------
-- PARTE B - NASCONDE GLI ANNUNCI (eseguire solo dopo aver guardato la parte A)
-- ---------------------------------------------------------------------------
update public.marketplace_listings
set status = 'removed_policy',
    updated_at = now()
where status in ('active', 'reserved')
  and public.listing_offers_animals(title, description);
"""


def main() -> int:
    outputs = {DART_PATH: render_dart(), SQL_PATH: render_sql()}
    if "--check" in sys.argv:
        stale = [
            str(path.relative_to(ROOT))
            for path, text in outputs.items()
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        if stale:
            print("Out of date, run scripts/maintenance/gen_animal_policy.py:", *stale)
            return 1
        return 0
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8", newline="\n")
        print("wrote", path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
