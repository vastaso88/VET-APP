"""Writes the SQL that loads the approved health cards into Supabase.

    python scripts/setup/export_health_cards_sql.py > .local/health_cards_load.sql
    (--include-drafts adds the cards still in draft, for a test database only)

Reads the manual project's export (data/manuale/health_cards.json), keeps the
approved cards (drafts only with --include-drafts, for a test database), and
prints an idempotent upsert for public.health_cards (scripts/setup/
health_cards.sql must have run first). The owner runs the output in the
Supabase SQL editor; nothing here connects to any database.
"""

from __future__ import annotations

import argparse
import sys
from datetime import UTC, datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from packages.core.domain.knowledge.health_cards import load_cards_file  # noqa: E402


def _quote(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--include-drafts", action="store_true")
    arguments = parser.parse_args()
    cards = load_cards_file(include_drafts=arguments.include_drafts)
    today = datetime.now(UTC).date().isoformat()
    print("-- generated by scripts/setup/export_health_cards_sql.py on", today)
    print("begin;")
    for card in cards:
        species = "array[" + ", ".join(_quote(s) for s in card.species) + "]::text[]"
        print(
            "insert into public.health_cards (id, species, topic, title, body, source, "
            "source_level, language, status, last_checked_at) values ("
            f"{_quote(card.id)}, {species}, {_quote(card.topic)}, {_quote(card.title)}, "
            f"{_quote(card.body)}, {_quote(card.source)}, {card.source_level}, "
            f"{_quote(card.language)}, {_quote(card.status)}, {_quote(today)}) "
            "on conflict (id) do update set species = excluded.species, topic = excluded.topic, "
            "title = excluded.title, body = excluded.body, source = excluded.source, "
            "source_level = excluded.source_level, language = excluded.language, "
            "status = excluded.status, last_checked_at = excluded.last_checked_at, "
            "updated_at = now();"
        )
    print("commit;")
    print(f"-- {len(cards)} cards", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
